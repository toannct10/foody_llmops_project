-- Render with: python -m scripts.cloud_foundation bootstrap-sql > foody_bootstrap.sql
-- Execute using a role permitted to create roles, warehouse, database, schemas,
-- stage and grants. The S3 storage integration must already exist and be trusted.
CREATE WAREHOUSE IF NOT EXISTS {{WAREHOUSE}} WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS {{DATABASE}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{RAW}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{STAGING}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{MART}};
CREATE ROLE IF NOT EXISTS FOODY_INGEST_ROLE;
CREATE ROLE IF NOT EXISTS FOODY_TRANSFORM_ROLE;
CREATE ROLE IF NOT EXISTS FOODY_AI_READONLY_ROLE;

CREATE FILE FORMAT IF NOT EXISTS {{DATABASE}}.{{RAW}}.FOODY_CSV
  TYPE = CSV ENCODING = 'UTF8' SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = FALSE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;
CREATE STAGE IF NOT EXISTS {{DATABASE}}.{{RAW}}.FOODY_S3_STAGE
  URL = 's3://{{BUCKET}}/{{PREFIX}}/'
  STORAGE_INTEGRATION = {{INTEGRATION}}
  FILE_FORMAT = {{DATABASE}}.{{RAW}}.FOODY_CSV;

-- Source fields remain text in RAW. Their order matches each accepted CSV.
CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{RAW}}.SALES_SOURCE (
  ORDER_ID VARCHAR, ORDER_DATE VARCHAR, SALES_AMOUNT VARCHAR,
  ORDER_STATUS VARCHAR, RESTAURANT_ID VARCHAR, RESTAURANT_NAME VARCHAR,
  SOURCE_FILE VARCHAR, SOURCE_HASH VARCHAR, BATCH_ID VARCHAR,
  LOADED_AT TIMESTAMP_TZ
);
CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{RAW}}.REVIEWS_SOURCE (
  REVIEW_TIME VARCHAR, RATING VARCHAR, COMMENT VARCHAR,
  RESTAURANT_ID VARCHAR, RESTAURANT_NAME VARCHAR, ADDRESS VARCHAR,
  SOURCE_FILE VARCHAR, SOURCE_HASH VARCHAR, BATCH_ID VARCHAR,
  LOADED_AT TIMESTAMP_TZ
);
CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{RAW}}.LOAD_AUDIT (
  SOURCE_NAME VARCHAR, BATCH_ID VARCHAR, SOURCE_HASH VARCHAR,
  SOURCE_FILE VARCHAR, S3_OBJECT_KEY VARCHAR, ROW_COUNT NUMBER,
  REJECTED_ROWS NUMBER, COPY_QUERY_ID VARCHAR, INSERT_QUERY_ID VARCHAR,
  LOADED_AT TIMESTAMP_TZ
);

GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE FOODY_INGEST_ROLE;
GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE FOODY_INGEST_ROLE;
GRANT USAGE ON SCHEMA {{DATABASE}}.{{RAW}} TO ROLE FOODY_INGEST_ROLE;
-- Required only for session-scoped temporary COPY landing tables.
GRANT CREATE TABLE ON SCHEMA {{DATABASE}}.{{RAW}} TO ROLE FOODY_INGEST_ROLE;
GRANT USAGE ON STAGE {{DATABASE}}.{{RAW}}.FOODY_S3_STAGE TO ROLE FOODY_INGEST_ROLE;
GRANT USAGE ON FILE FORMAT {{DATABASE}}.{{RAW}}.FOODY_CSV TO ROLE FOODY_INGEST_ROLE;
GRANT SELECT, INSERT ON TABLE {{DATABASE}}.{{RAW}}.SALES_SOURCE TO ROLE FOODY_INGEST_ROLE;
GRANT SELECT, INSERT ON TABLE {{DATABASE}}.{{RAW}}.REVIEWS_SOURCE TO ROLE FOODY_INGEST_ROLE;
GRANT SELECT, INSERT ON TABLE {{DATABASE}}.{{RAW}}.LOAD_AUDIT TO ROLE FOODY_INGEST_ROLE;

GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT USAGE ON SCHEMA {{DATABASE}}.{{RAW}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT USAGE ON SCHEMA {{DATABASE}}.{{STAGING}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT USAGE ON SCHEMA {{DATABASE}}.{{MART}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT SELECT ON TABLE {{DATABASE}}.{{RAW}}.SALES_SOURCE TO ROLE FOODY_TRANSFORM_ROLE;
GRANT SELECT ON TABLE {{DATABASE}}.{{RAW}}.REVIEWS_SOURCE TO ROLE FOODY_TRANSFORM_ROLE;
GRANT SELECT ON TABLE {{DATABASE}}.{{RAW}}.LOAD_AUDIT TO ROLE FOODY_TRANSFORM_ROLE;
GRANT CREATE TABLE ON SCHEMA {{DATABASE}}.{{STAGING}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT CREATE TABLE ON SCHEMA {{DATABASE}}.{{MART}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT CREATE VIEW ON SCHEMA {{DATABASE}}.{{STAGING}} TO ROLE FOODY_TRANSFORM_ROLE;
GRANT CREATE VIEW ON SCHEMA {{DATABASE}}.{{MART}} TO ROLE FOODY_TRANSFORM_ROLE;

GRANT USAGE ON WAREHOUSE {{WAREHOUSE}} TO ROLE FOODY_AI_READONLY_ROLE;
GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE FOODY_AI_READONLY_ROLE;
GRANT USAGE ON SCHEMA {{DATABASE}}.{{MART}} TO ROLE FOODY_AI_READONLY_ROLE;
-- Apply only explicit MART grants after dbt creates the approved relations.
